def about(P, only=None):
    for t in P.tools():
        if only and t['id'] != only:
            continue
        print('%s  (%s, %s, %s)  %s' % (t['name'], t['id'], t['origin'], 'ships live' if t.get('ships') == 'live' else 'studio only', t.get('page', '')))
        for k in ('what', 'when'):
            print('  %-8s %s' % (k + ':', t.get(k, '')))
        print('  reads:   ' + ', '.join(t.get('sources', [])))
        print('  writes:  ' + ', '.join(t.get('outputs', [])))
        print('  run:     ' + ' && '.join(t.get('run', [])))
        if t.get('skill'):
            print('  skill:   .claude/skills/%s/SKILL.md' % t['skill'])
        if t.get('production_only'):
            print('  note:    production copy only (left out of the other copies to stay under the Pages size limit)')
        print()
    if not only:
        r = P.cfg['release']
        print('Project: %s (studio kit %s in %s/)' % (P.cfg['project']['name'], P.kitinfo['version'], P.kit_rel))
        print('Release: ' + ', '.join('%s %s' % (k, 'tooled' if v else 'LIVE (no studio)') for k, v in r.items() if isinstance(v, bool)))
        print('Skills:  ' + ', '.join(s['name'] for s in P.skills()))


def git(P, *a):
    try:
        return subprocess.run(['git', '-C', P.root] + list(a), capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return ''


def changed_at(P, paths):
    paths = [p.split(' ')[0].split('*')[0].split('<')[0].rstrip('/') for p in paths]
    paths = [p for p in paths if p and os.path.exists(P.path(p))]
    if not paths:
        return 0, ''
    best = 0
    for l in git(P, 'status', '--porcelain', '--', *paths).splitlines():
        f = P.path(l[3:].strip().strip('"'))
        if os.path.isfile(f):
            best = max(best, os.path.getmtime(f))
    if best:
        return best, 'uncommitted'
    t = git(P, 'log', '-1', '--format=%ct', '--', *paths)
    return (int(t), 'committed') if t else (0, '')


def history_state(P):
    idx = P.path(P.cfg['data']['history'], 'index.json')
    br = P.cfg['history']['branch']
    head = git(P, 'rev-parse', '--short=7', 'origin/' + br) or git(P, 'rev-parse', '--short=7', br)  # what history.py reads
    last = ''
    if os.path.exists(idx):
        cs = json.load(open(idx, encoding='utf8')).get('commits', [])
        last = (cs[-1].get('c') or '')[:7] if cs else ''
    return (not head or (last and head.startswith(last))), last, head


def status(P):
    stale = edited = 0
    for t in P.tools():
        if t['id'] == 'history':
            ok, last, head = history_state(P)
            print('%-16s %s' % (t['name'], 'current' if ok else 'behind %s (%s, %s is %s): %s' % (
                P.cfg['history']['branch'], last or 'none', P.cfg['history']['branch'], head, ' && '.join(t['run']))))
            stale += not ok
            continue
        s, how = changed_at(P, t.get('sources', []))
        o, ohow = changed_at(P, t.get('outputs', []))
        if how == 'uncommitted' and ohow != 'uncommitted':
            edited += 1
            print('%-16s sources edited, not committed: refresh before you commit (%s)' % (t['name'], ' && '.join(t.get('run', []))))
        elif s and o and s > o + 1:
            stale += 1
            print('%-16s sources changed after outputs: %s' % (t['name'], ' && '.join(t.get('run', []))))
        else:
            print('%-16s current' % t['name'])
    if stale or edited:
        print('\n%d tool(s) to refresh, %d with uncommitted edits: python %s/studio.py refresh' % (stale, edited, P.kit_rel))
    else:
        print('\nEverything current. python %s/studio.py check before you push.' % P.kit_rel)


# ================================================================ refresh

def has_pillow():
    try:
        import PIL  # noqa: F401
        return True
    except ImportError:
        return False


def steps(P):
    """Kit steps, then the project's (config refresh), then the bar. Each: id, label, run, tools, needs."""
    k = P.kit_rel
    c = P.cfg
    out = [{'id': 'pages', 'label': 'page index', 'run': [PY, k + '/studio.py', 'pages'], 'tools': ['*']}]
    if c['images'].get('webp'):
        out.append({'id': 'webp', 'label': 'WebP copies of PNG images', 'run': [PY, k + '/tools/images/webp.py'] + c['images']['webp'],
                    'tools': ['gallery', 'site'], 'pillow': True})
    out.append({'id': 'gallery', 'label': 'media gallery', 'run': [PY, k + '/studio.py', 'gallery'], 'tools': ['gallery', 'atlas'], 'pillow': True})
    out.append({'id': 'atlas', 'label': 'style atlas', 'run': [PY, k + '/studio.py', 'atlas'], 'tools': ['atlas']})
    for s in c.get('refresh', []):
        out.append(dict(s, run=argv(s['run'])))
    out.append({'id': 'build', 'label': 'studio bar', 'run': [PY, k + '/studio.py', 'build'], 'tools': ['*']})
    return out


def refresh(P, only, history=False):
    pil = has_pillow()
    for s in steps(P):
        if only and '*' not in s.get('tools', []) and not set(only) & set(s.get('tools', [])) and s['id'] not in only:
            continue
        if s.get('pillow') and not pil:
            print('-- skip %s: needs Pillow (pip install Pillow)' % s['label'])
            continue
        if s.get('needs_path') and not os.path.exists(P.path(s['needs_path'])):
            print('-- skip %s: %s is not there (see studio.config.json refresh)' % (s['label'], s['needs_path']))
            continue
        print('-- %s: %s' % (s['label'], ' '.join(os.path.basename(x) if x == PY else x for x in s['run'])))
        if subprocess.run(s['run'], cwd=P.root, env=env(P)).returncode:
            sys.exit('failed: ' + ' '.join(s['run']))
    if history or (only and 'history' in only):
        print('-- page history')
        subprocess.run([PY, P.kit_rel + '/studio.py', 'history'], cwd=P.root, check=True)
    print('-- checks')
    bad = 0
    for c in P.cfg.get('checks', []):
        bad |= subprocess.run(argv(c), cwd=P.root).returncode
    bad |= check(P)
    if bad:
        sys.exit(1)


# ================================================================ release

def keep_files(src, keep):
    out, unmatched = [], []
    for pat in keep:
        hits = []
        if pat.endswith('/'):
            for d, _, fs in os.walk(os.path.join(src, pat)):
                hits += [os.path.relpath(os.path.join(d, f), src).replace(os.sep, '/') for f in fs]
        elif any(ch in pat for ch in '*?['):
            base = pat.split('*')[0].rsplit('/', 1)[0] if '/' in pat.split('*')[0] else ''
            for d, _, fs in os.walk(os.path.join(src, base) if base else src):
                for f in fs:
                    r = os.path.relpath(os.path.join(d, f), src).replace(os.sep, '/')
                    if fnmatch.fnmatch(r, pat) and not r.startswith('.git/'):
                        hits.append(r)
        elif os.path.isfile(os.path.join(src, pat)):
            hits = [pat]
        if not hits:
            unmatched.append(pat)
        out += hits
    return sorted(set(out)), unmatched


def strip_studio(html):
    return re.sub(re.escape(MARK_A) + r'.*?' + re.escape(MARK_B) + r'\n?', '', html, flags=re.S)


def release(out, src, keep, quiet=False):
    files, unmatched = keep_files(src, keep)
    o, s = os.path.realpath(out), os.path.realpath(src)
    if o == s or s.startswith(o + os.sep) or os.path.exists(os.path.join(out, '.git')):
        sys.exit('release: %s holds the source; choose an empty output folder outside it' % out)
    if os.path.exists(out):
        shutil.rmtree(out)
    size = 0
    for f in files:
        d = os.path.join(out, f)
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copy2(os.path.join(src, f), d)
        if f.endswith(('.html', '.htm')):
            html = strip_studio(open(d, encoding='utf8', errors='replace').read())
            open(d, 'w', encoding='utf8', newline='\n').write(html)
        size += os.path.getsize(d)
    if not quiet:
        print('released %d files, %.1f MB, into %s' % (len(files), size / 1e6, out))
        for u in unmatched:
            print('  keep pattern matched nothing: ' + u)
    return files, unmatched


URL_RX = re.compile(r'''(?:href|src)=["']([^"'#?]+)|fetch\(\s*['"]([^'"?]+)|url\(\s*['"]?([^'")?#]+)''')


def release_problems(P, out):
    problems = []
    entry = P.cfg['site']['entry']
    ip = os.path.join(out, entry)
    if not os.path.exists(ip) or os.path.getsize(ip) < 64:
        problems.append('the released site has no %s (or it is empty)' % entry)
    tool_pages = {t['page'].split('#')[0] for t in P.tools() if t.get('ships') != 'live' and t.get('page')}
    for d, _, fs in os.walk(out):
        for f in fs:
            p = os.path.join(d, f)
            r = os.path.relpath(p, out).replace(os.sep, '/')
            if r.startswith(P.kit_rel + '/') or r in tool_pages or r == config.CONFIG_NAME:
                problems.append('studio file in the live site: ' + r)
            if not f.endswith(('.html', '.htm', '.css')):
                continue
            txt = open(p, encoding='utf8', errors='replace').read()
            if f.endswith(('.html', '.htm')):
                if MARK_A in txt or (P.kit_rel + '/web/studio') in txt:
                    problems.append('%s still loads the studio (wrap it in <!-- studio: --> ... <!-- /studio -->)' % r)
                for tp in tool_pages:
                    if re.search(r'''(href|src)=["']%s''' % re.escape(tp), txt):
                        problems.append('%s links to the studio page %s' % (r, tp))
            for m in URL_RX.finditer(txt):
                u = next(g for g in m.groups() if g)
                if re.match(r'^(https?:|data:|mailto:|tel:|//|#|javascript:|/)', u) or '+' in u or '{' in u or not u.strip():
                    continue
                if not os.path.exists(os.path.normpath(os.path.join(os.path.dirname(p), u))):
                    problems.append('%s points at %s, which the live site does not have (add it to live.keep)' % (r, u))
    for d, _, fs in os.walk(out):
        for f in fs:
            if f.endswith('.js'):
                p = os.path.join(d, f)
                for folder in sorted(set(re.findall(r"['\"]((?:assets|brand|images|img)/[a-z0-9_-]+/)", open(p, encoding='utf8', errors='replace').read()))):
                    if not os.path.isdir(os.path.join(out, folder)):
                        problems.append('%s builds paths into %s, which the live site does not have' % (os.path.relpath(p, out), folder))
    return problems


# ================================================================ check

def check(P):
    c = P.cfg
    problems = []
    if not P.has_config:
        problems.append('no studio.config.json at the project root: python %s/studio.py init' % P.kit_rel)
    ids = set()
    for t in P.tools():
        for k in ('id', 'name', 'what', 'when', 'sources', 'outputs', 'run'):
            if k not in t:
                problems.append('tool %s has no "%s"' % (t.get('id', '?'), k))
        if t['id'] in ids:
            problems.append('duplicate tool id: ' + t['id'])
        ids.add(t['id'])
        if not t.get('page'):
            continue
        page = P.path(t['page'].split('#')[0])
        if not os.path.isfile(page):
            problems.append('tool %s: page %s is missing' % (t['id'], t['page']))
            continue
        html = open(page, encoding='utf8', errors='replace').read()
        if t['origin'] == 'project':
            js = P.kit_rel + '/web/studio.js'
            if not re.search(r'''<script[^>]*src=["']%s[^"']*["'][^>]*data-tool=["']%s["']''' % (re.escape(js), re.escape(t['id'])), html):
                problems.append('%s does not load the studio bar: <script defer src="%s" data-tool="%s"></script>' % (t['page'].split('#')[0], js, t['id']))
            if P.kit_rel + '/web/studio.css' not in html:
                problems.append('%s does not load %s/web/studio.css' % (t['page'].split('#')[0], P.kit_rel))
        if t.get('skill') and t['skill'] not in {s['name'] for s in P.skills()}:
            problems.append('tool %s names skill %s, which is neither a kit skill nor in config "skills"' % (t['id'], t['skill']))
    for s in P.skills():
        if not os.path.isfile(P.path(s['path'])):
            problems.append('skill %s: %s is missing%s' % (s['name'], s['path'], ' (python %s/studio.py install)' % P.kit_rel if s['origin'] == 'kit' else ''))
        elif s['origin'] == 'kit':
            a = open(os.path.join(P.kit, 'skills', s['name'], 'SKILL.md'), encoding='utf8').read()
            if open(P.path(s['path']), encoding='utf8').read() != a:
                problems.append('skill %s differs from the kit copy in %s/skills/ (edit the kit copy, then python %s/studio.py install)' % (s['name'], P.kit_rel, P.kit_rel))
    sk = P.path('.claude', 'skills')
    if os.path.isdir(sk):
        for d in sorted(os.listdir(sk)):
            if d not in {s['name'] for s in P.skills()}:
                problems.append('skill %s is in .claude/skills/ but neither a kit skill nor in studio.config.json "skills"' % d)
    for k, v in c['notes'].items():
        if not os.path.isfile(P.path(v)):
            problems.append('notes.%s: %s is missing' % (k, v))
    js = os.path.join(P.kit, 'web', 'studio.js')
    if not os.path.exists(js) or open(js, encoding='utf8').read() != bar_js(P):
        problems.append('%s/web/studio.js is out of date: python %s/studio.py build' % (P.kit_rel, P.kit_rel))
    hj = P.path(c['data']['dir'], 'studio.json')
    if not os.path.exists(hj) or open(hj, encoding='utf8').read() != hub_json(P):
        problems.append('%s is out of date: python %s/studio.py build' % (P.rel(hj), P.kit_rel))
    hsw = P.path(c['data']['history'], 'sw.js')
    if os.path.exists(hsw) and open(hsw, encoding='utf8').read() != open(os.path.join(P.kit, 'web', 'history-sw.js'), encoding='utf8').read():
        problems.append('%s is out of date: python %s/studio.py build' % (P.rel(hsw), P.kit_rel))
    # the site: the studio only ever inside its blocks
    entry = P.path(c['site']['entry'])
    if os.path.exists(entry):
        html = open(entry, encoding='utf8').read()
        if html.count(MARK_A) != html.count(MARK_B):
            problems.append('%s: unbalanced <!-- studio: --> / <!-- /studio --> markers' % c['site']['entry'])
        if html.count(MARK_A) == 0:
            problems.append('%s does not load the studio bar (python %s/studio.py install adds it)' % (c['site']['entry'], P.kit_rel))
        if (P.kit_rel + '/') in strip_studio(html):
            problems.append('%s reaches the studio outside a studio block (the live site would break)' % c['site']['entry'])
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'live')
        _, unmatched = release(out, P.root, c['live']['keep'], quiet=True)
        problems += ['live.keep pattern matches nothing: ' + u for u in unmatched]
        problems += release_problems(P, out)
    for p in problems:
        print('STUDIO', p)
    print('studio: %d problem(s), %d tools, %d skills, release dry run %s' % (
        len(problems), len(P.tools()), len(P.skills()), 'clean' if not problems else 'see above'))
    return 1 if problems else 0


# ================================================================ assemble (GitHub Pages)

def copytree(src, dst, exclude=()):
    ex = {'.git', '.github'} | set(exclude)

    def ignore(d, names):
        r = os.path.relpath(d, src).replace(os.sep, '/')
        return [n for n in names if n in ex or (r + '/' + n if r != '.' else n) in ex]
    shutil.copytree(src, dst, ignore=ignore, dirs_exist_ok=True)


def label_copy(dst, name):
    """Checkouts from before the studio name their copy in the old draft bar text."""
    p = os.path.join(dst, 'index.html')
    if os.path.exists(p):
        s = open(p, encoding='utf8').read()
        open(p, 'w', encoding='utf8', newline='\n').write(s.replace('Draft site · not for release · ', '%s copy · draft site · not for release · ' % name))


def project_at(src, fallback):
    try:
        return config.Project(src) if os.path.isfile(os.path.join(src, config.CONFIG_NAME)) else fallback
    except Exception:
        return fallback


def legacy_keep(src):
    """Before the kit, the keep list lived in studio/manifest.json."""
    p = os.path.join(src, 'studio', 'manifest.json')
    return json.load(open(p, encoding='utf8'))['live']['keep'] if os.path.exists(p) else None


def assemble(P, site, dirs):
    """dirs: {copy id or branch: checkout}. Production is the copy with path ''."""
    os.makedirs(site, exist_ok=True)
    copies = P.cfg['copies']
    prod = next(c for c in copies if c['path'] == '')
    main = dirs.get(prod['id']) or dirs.get(prod['branch'])
    PM = project_at(main, P)
    heavy = PM.cfg['release'].get('heavy', [])
    keep = (PM.cfg['live']['keep'] if PM.has_config else None) or legacy_keep(main) or P.cfg['live']['keep']
    if PM.cfg['release'].get('production', True):
        copytree(main, site)
        print('production: tooled draft (%s)' % prod['branch'])
    else:
        release(site, main, keep)
        print('production: LIVE site; tooled %s at draft/' % prod['branch'])
    for c in copies:
        if c['path'] == '':
            continue
        if c['id'] == 'live':
            release(os.path.join(site, c['path']), main, keep)
            print('live: released %s, for review before the switch' % c['branch'])
            continue
        if c['id'] == 'draft':
            if not PM.cfg['release'].get('production', True):
                copytree(main, os.path.join(site, c['path']))
                print('draft: tooled %s' % c['branch'])
            continue
        src = dirs.get(c['id']) or dirs.get(c['branch'])
        if not src or not os.path.isdir(src):
            print('%s: no checkout given, skipped' % c['id'])
            continue
        PB = project_at(src, P)
        dst = os.path.join(site, c['path'])
        if PB.cfg['release'].get(c['id'], True):
            copytree(src, dst, PB.cfg['release'].get('heavy', heavy))
            label_copy(dst, c.get('label', c['id']).split(' ')[0])
            print('%s: tooled (without %s)' % (c['id'], ', '.join(PB.cfg['release'].get('heavy', heavy)) or 'nothing'))
        else:
            release(dst, src, PB.cfg['live']['keep'])
            print('%s: LIVE' % c['id'])
    open(os.path.join(site, '.nojekyll'), 'w').close()


# ================================================================ install / init / doctor

SNIPPET_A, SNIPPET_B = '<!-- studio-kit -->', '<!-- /studio-kit -->'


def install(P, quiet=False):
    """Put the kit's skills where Claude Code finds them, and point the project's agent files at the kit."""
    n = 0
    for s in P.kitinfo['skills']:
        src = os.path.join(P.kit, 'skills', s['name'])
        dst = P.path('.claude', 'skills', s['name'])
        os.makedirs(dst, exist_ok=True)
        for f in os.listdir(src):
            if write(os.path.join(dst, f), open(os.path.join(src, f), encoding='utf8').read()):
                n += 1
    snippet = open(os.path.join(P.kit, 'templates', 'agents-snippet.md'), encoding='utf8').read().replace('{kit}', P.kit_rel)
    block = SNIPPET_A + '\n' + snippet.strip() + '\n' + SNIPPET_B + '\n'
    for name in ('CLAUDE.md', 'AGENTS.md'):
        p = P.path(name)
        if not os.path.exists(p):
            if name == 'AGENTS.md':
                write(p, '# Working in this repository\n\n' + block)
                n += 1
            continue
        s = open(p, encoding='utf8').read()
        if name == 'CLAUDE.md' and '@AGENTS.md' in s and SNIPPET_A not in s:
            continue  # CLAUDE.md imports AGENTS.md, which carries the section
        new = re.sub(re.escape(SNIPPET_A) + '.*?' + re.escape(SNIPPET_B) + r'\n?', lambda m: block, s, flags=re.S) if SNIPPET_A in s else s.rstrip() + '\n\n' + block
        if write(p, new):
            n += 1
    if not os.path.exists(P.path('CLAUDE.md')):
        write(P.path('CLAUDE.md'), '@AGENTS.md\n')
    if not quiet:
        print('installed %d kit skill(s) into .claude/skills/ and the studio section of AGENTS.md / CLAUDE.md (%d file(s) changed)' % (len(P.kitinfo['skills']), n))


def init(root, name=None, force=False):
    """Start a project on the kit: write studio.config.json from what is there, wire the bar into the entry page."""
    root = os.path.abspath(root)
    p = os.path.join(root, config.CONFIG_NAME)
    if os.path.exists(p) and not force:
        print('studio.config.json is already there; editing it is the next step (or --force to start over)')
    else:
        tpl = json.load(open(os.path.join(config.KIT, 'templates', 'studio.config.json'), encoding='utf8'))
        tpl['project']['name'] = name or os.path.basename(root).replace('-', ' ').replace('_', ' ').title()
        url = subprocess.run(['git', '-C', root, 'remote', 'get-url', 'origin'], capture_output=True, text=True).stdout.strip()
        m = re.search(r'github\.com[:/]([^/]+)/([^/.]+)', url)
        if m:
            tpl['project']['repo'] = '%s/%s' % m.groups()
            tpl['project']['url'] = 'https://%s.github.io/%s/' % (m.group(1).lower(), m.group(2))
        entry = 'index.html' if os.path.exists(os.path.join(root, 'index.html')) else next(
            (f for f in sorted(os.listdir(root)) if f.endswith('.html')), 'index.html')
        tpl['site']['entry'] = entry
        keep = sorted(f for f in os.listdir(root) if f.endswith(('.html', '.css', '.js', '.ico', '.svg', '.png', '.webmanifest', '.txt', '.xml'))
                      and f not in (config.CONFIG_NAME,))
        keep += sorted(d + '/' for d in os.listdir(root) if os.path.isdir(os.path.join(root, d)) and d in
                       ('assets', 'css', 'js', 'img', 'images', 'fonts', 'media', 'static', 'public', 'content', 'pages', 'blog'))
        tpl['live']['keep'] = keep or ['index.html']
        br = subprocess.run(['git', '-C', root, 'symbolic-ref', '--short', 'refs/remotes/origin/HEAD'], capture_output=True, text=True).stdout.strip()
        if br:
            b = br.split('/', 1)[1]
            tpl['history']['branch'] = b
            tpl['branches']['production'] = b
            for c in tpl['copies']:
                c['branch'] = b
        write(p, json.dumps(tpl, indent=1, ensure_ascii=False) + '\n')
        print('wrote studio.config.json for %s (entry %s, %d live.keep entries): review it' % (tpl['project']['name'], entry, len(tpl['live']['keep'])))
    P = config.Project(root)
    # the bar on every site page (multi-page sites) inside a studio block
    tag = ('<!-- studio: development tooling (studio.config.json). python {k}/studio.py release removes this block for the live site. -->\n'
           '<link rel="stylesheet" href="{r}{k}/web/studio.css">\n<script defer src="{r}{k}/web/studio.js" data-tool="site"></script>\n<!-- /studio -->\n')
    wired = 0
    for pg in pagesmod.collect(P):
        f = P.path(pg['file'])
        if not pg.get('file', '').endswith(('.html', '.htm')) or not os.path.isfile(f):
            continue
        s = open(f, encoding='utf8', errors='replace').read()
        if MARK_A in s or '</head>' not in s:
            continue
        up = '../' * pg['file'].count('/')
        s = s.replace('</head>', tag.format(k=P.kit_rel, r=up) + '</head>', 1)
        write(f, s)
        wired += 1
    print('added the studio bar to %d page(s)' % wired)
    for d in ('dir',):
        os.makedirs(P.path(P.cfg['data'][d]), exist_ok=True)
    install(P)
    build(P)


