"""The Aquemi studio: every development tool beside the website, run, checked and detached from one place.
Python 3 standard library only (the image steps of `refresh` use Pillow when it is there and are skipped when not).

  python tools/studio.py                      Same as `about`.
  python tools/studio.py about [tool]         What each tool is, when to use it, what it reads and writes, how to refresh
                                              it, its agent skill and whether it ships (studio/manifest.json, "tools").
  python tools/studio.py status               Which tools have sources newer than their outputs, from git and the
                                              working tree, and what to run for each.
  python tools/studio.py refresh [tool ...]   Run the generators in order (images, gallery, section snapshot, research,
         [--history]                          design-system build), then `check`. Name tools to refresh only those.
                                              --history also rebuilds the page history (main only, slow).
  python tools/studio.py build                Write studio/studio.js (the studio bar) from studio/src/bar.js and the
                                              manifest. tools/design_system.py build calls this; no need to run it alone.
  python tools/studio.py check                The studio's rules: manifest, every tool page carries the bar, the bar is
                                              current, and a dry-run release leaves no studio file and no broken link.
  python tools/studio.py release <out>        Write the live site into <out>: only manifest "live.keep", the studio
         [--from <checkout>]                  block cut from index.html. Read-only on the source.
  python tools/studio.py assemble <site>      Build the GitHub Pages site from checkouts of the three branches
         --main <dir> --staging <dir>         (.github/workflows/pages.yml): each copy tooled or released per its own
         --dev <dir>                          manifest "release", and /live/, the released main, always.

studio/manifest.json is the registry; studio/README.md is the guide for people and agents.
"""
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'studio', 'manifest.json')
BAR_SRC = os.path.join(ROOT, 'studio', 'src', 'bar.js')
BAR_OUT = os.path.join(ROOT, 'studio', 'studio.js')
MARK_A, MARK_B = '<!-- studio:', '<!-- /studio -->'
PY = sys.executable or 'python3'
# Left out of the tooled staging and dev copies, to keep the Pages site under its size limit (production carries them)
HEAVY = ['versions', 'design-system/inspiration']


def load(root=ROOT):
    p = os.path.join(root, 'studio', 'manifest.json')
    return json.load(open(p, encoding='utf8')) if os.path.exists(p) else None


def rel(p, root=ROOT):
    return os.path.relpath(p, root).replace(os.sep, '/')


# ---------------------------------------------------------------- build

def bar_js(m=None):
    m = m or load()
    slim = {'release': {k: v for k, v in m['release'].items() if k != 'about'},
            'copies': [{'id': c['id'], 'path': c['path']} for c in m['copies']],
            'tools': [{k: t[k] for k in ('id', 'name', 'page', 'what', 'production_only') if k in t} for t in m['tools']]}
    src = open(BAR_SRC, encoding='utf8').read()
    head = '/* Generated by tools/studio.py build from studio/src/bar.js and studio/manifest.json. Do not edit. */\n'
    return head + src.replace('/*@MANIFEST@*/null', json.dumps(slim, ensure_ascii=False, separators=(',', ':')))


def build():
    open(BAR_OUT, 'w', encoding='utf8', newline='\n').write(bar_js())
    print('wrote studio/studio.js (studio bar, %d tools)' % len(load()['tools']))


# ---------------------------------------------------------------- about / status

def about(only=None):
    m = load()
    for t in m['tools']:
        if only and t['id'] != only:
            continue
        print('%s  (%s, %s)  %s' % (t['name'], t['id'], 'ships live' if t['ships'] == 'live' else 'studio only', t['page']))
        print('  what:    ' + t['what'])
        print('  when:    ' + t['when'])
        print('  reads:   ' + ', '.join(t['sources']))
        print('  writes:  ' + ', '.join(t['outputs']))
        print('  run:     ' + ' && '.join(t['run']))
        print('  skill:   .claude/skills/%s/SKILL.md' % t['skill'])
        if t.get('production_only'):
            print('  note:    production copy only (left out of staging and dev to stay under the Pages size limit)')
        print()
    if not only:
        r = m['release']
        print('Release: ' + ', '.join('%s %s' % (k, 'tooled' if v else 'LIVE (no studio)') for k, v in r.items() if k != 'about'))
        print('Skills:  ' + ', '.join(s['name'] for s in m['skills']))


def git(*a, root=ROOT):
    try:
        return subprocess.run(['git'] + list(a), cwd=root, capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        return ''


def changed_at(paths):
    """Latest change to any of the paths: the uncommitted time if the working tree changed one, else its last commit."""
    paths = [p.split(' ')[0] for p in paths if os.path.exists(os.path.join(ROOT, p.split('*')[0].split(' ')[0].rstrip('/')) or '.')]
    paths = [p for p in paths if p]
    if not paths:
        return 0, ''
    dirty = [l[3:] for l in git('status', '--porcelain', '--', *paths).splitlines() if l.strip()]
    best = 0
    for d in dirty:
        f = os.path.join(ROOT, d.strip('"'))
        if os.path.isfile(f):
            best = max(best, os.path.getmtime(f))
    if best:
        return best, 'uncommitted'
    t = git('log', '-1', '--format=%ct', '--', *paths)
    return (int(t), 'committed') if t else (0, '')


def status():
    m = load()
    stale = 0
    for t in m['tools']:
        if t['id'] == 'history':
            idx = os.path.join(ROOT, 'versions', 'index.json')
            head = git('rev-parse', '--short=7', 'origin/main') or git('rev-parse', '--short=7', 'main')
            last = ''
            if os.path.exists(idx):
                cs = json.load(open(idx, encoding='utf8')).get('commits', [])
                last = (cs[-1].get('c') or cs[-1].get('h') or '')[:7] if cs else ''
            ok = not head or (last and head.startswith(last[:7]))
            print('%-16s %s' % (t['name'], 'current' if ok else 'behind main (%s, main is %s): python tools/versions.py on main' % (last or 'none', head)))
            stale += not ok
            continue
        s, how = changed_at(t['sources'])
        o, _ = changed_at(t['outputs'])
        if s and o and s > o + 1:
            stale += 1
            print('%-16s sources changed (%s) after outputs: %s' % (t['name'], how, ' && '.join(t['run'])))
        else:
            print('%-16s current' % t['name'])
    print('\n%d tool(s) to refresh' % stale if stale else '\nEverything current. python tools/studio.py check before you push.')


# ---------------------------------------------------------------- refresh

def has_pillow():
    try:
        import PIL  # noqa: F401
        return True
    except ImportError:
        return False


STEPS = [  # (tool ids that need it, label, command, needs Pillow)
    (('gallery', 'site'), 'equipment drawings to WebP', ['tools/images.py'], True),
    (('gallery', 'research'), 'media gallery manifest and thumbnails', ['tools/gallery.py'], True),
    (('sections', 'site'), 'section library snapshot', ['tools/specimens.py', 'snapshot'], False),
    (('research',), 'design research page', ['tools/research.py'], False),
    (('guide', 'sections', 'site', 'studio', 'gallery', 'research'), 'design system build (site, guide, library, studio bar)', ['tools/design_system.py', 'build'], False),
]


def refresh(only, history=False):
    pil = has_pillow()
    for tools, label, cmd, needs_pil in STEPS:
        if only and not set(only) & set(tools):
            continue
        if cmd[0] == 'tools/research.py' and not os.path.isdir(os.path.join(os.path.dirname(ROOT), 'research')):
            print('-- skip %s: the working folder ../research is not beside this checkout, and research.html holds build '
                  'notes only that folder has (run python tools/research.py where it is)' % label)
            continue
        if needs_pil and not pil:
            print('-- skip %s: needs Pillow (pip install Pillow)' % label)
            continue
        print('-- %s: python %s' % (label, ' '.join(cmd)))
        r = subprocess.run([PY] + cmd, cwd=ROOT)
        if r.returncode:
            sys.exit('failed: python ' + ' '.join(cmd))
    if history or (only and 'history' in only):
        print('-- page history: python tools/versions.py')
        subprocess.run([PY, 'tools/versions.py'], cwd=ROOT, check=True)
    print('-- check')
    a = subprocess.run([PY, 'tools/design_system.py', 'check'], cwd=ROOT).returncode
    b = check()
    if a or b:
        sys.exit(1)


# ---------------------------------------------------------------- release

def keep_files(src, m):
    """Every file the live site is made of: manifest live.keep, matched in <src>."""
    out, unmatched = [], []
    for pat in m['live']['keep']:
        hits = []
        if pat.endswith('/'):
            base = os.path.join(src, pat)
            for d, _, fs in os.walk(base):
                hits += [rel(os.path.join(d, f), src) for f in fs]
        elif '*' in pat:
            d = os.path.join(src, os.path.dirname(pat))
            if os.path.isdir(d):
                hits = [rel(os.path.join(d, f), src) for f in os.listdir(d)
                        if fnmatch.fnmatch(f, os.path.basename(pat)) and os.path.isfile(os.path.join(d, f))]
        elif os.path.isfile(os.path.join(src, pat)):
            hits = [pat]
        if not hits:
            unmatched.append(pat)
        out += hits
    return sorted(set(out)), unmatched


def strip_studio(html):
    return re.sub(re.escape(MARK_A) + r'.*?' + re.escape(MARK_B) + r'\n?', '', html, flags=re.S)


def release(out, src=ROOT, m=None, quiet=False):
    m = m or load(src) or load()
    files, unmatched = keep_files(src, m)
    o, s = os.path.realpath(out), os.path.realpath(src)
    if o == s or s.startswith(o + os.sep) or os.path.exists(os.path.join(out, '.git')):
        sys.exit('release: %s holds the source; choose an empty output folder outside it' % out)
    if os.path.exists(out):
        shutil.rmtree(out)
    size = 0
    for f in files:
        d = os.path.join(out, f)
        os.makedirs(os.path.dirname(d), exist_ok=True)
        shutil.copy2(os.path.join(src, f), d)
        size += os.path.getsize(d)
    ip = os.path.join(out, 'index.html')
    if os.path.exists(ip):
        html = strip_studio(open(ip, encoding='utf8').read())
        open(ip, 'w', encoding='utf8', newline='\n').write(html)
    if not quiet:
        print('released %d files, %.1f MB, into %s' % (len(files), size / 1e6, out))
        for u in unmatched:
            print('  keep pattern matched nothing: ' + u)
    return files, unmatched


URL_RX = re.compile(r'''(?:href|src)=["']([^"'#?]+)|fetch\(\s*['"]([^'"?]+)|url\(\s*['"]?([^'")?#]+)''')


def release_problems(out, m):
    """Studio left in the released site, and links in it that point at nothing."""
    problems = []
    ip = os.path.join(out, 'index.html')
    idx = open(ip, encoding='utf8').read() if os.path.exists(ip) else ''
    for need in ('id="wsite"', 'assets/aquemi-site.js', 'aq:render'):
        if need not in idx:
            problems.append('the released index.html lost %s: the studio block cut took the site with it' % need)
    tool_pages = {t['page'].split('#')[0] for t in m['tools'] if t['ships'] != 'live'}
    for d, _, fs in os.walk(out):
        for f in fs:
            p = os.path.join(d, f)
            r = rel(p, out)
            if r.startswith('studio/') or r in tool_pages:
                problems.append('studio file in the live site: ' + r)
            if not f.endswith(('.html', '.css')):
                continue
            txt = open(p, encoding='utf8', errors='replace').read()
            if f.endswith('.html'):
                if MARK_A in txt or 'studio/studio' in txt:
                    problems.append('%s still loads the studio' % r)
                for tp in tool_pages:
                    if re.search(r'''(href|src)=["']%s''' % re.escape(tp), txt):
                        problems.append('%s links to the studio page %s' % (r, tp))
            for mt in URL_RX.finditer(txt):
                u = next(g for g in mt.groups() if g)
                if re.match(r'^(https?:|data:|mailto:|tel:|//|#|javascript:)', u) or '+' in u or not u.strip():
                    continue
                target = os.path.normpath(os.path.join(os.path.dirname(p), u))
                if not os.path.exists(target):
                    problems.append('%s points at %s, which the live site does not have (add it to live.keep)' % (r, u))
    # files the site script names (illustrations, icons): every asset folder it builds paths into must have shipped
    for js in ('assets/aquemi-site.js', 'assets/motion.js'):
        p = os.path.join(out, js)
        if os.path.exists(p):
            for folder in sorted(set(re.findall(r"['\"]((?:assets|brand)/[a-z-]+/)", open(p, encoding='utf8').read()))):
                if not os.path.isdir(os.path.join(out, folder)):
                    problems.append('%s builds paths into %s, which the live site does not have' % (js, folder))
    return problems


# ---------------------------------------------------------------- check

def check():
    m = load()
    problems = []
    for k in ('release', 'live', 'tools', 'skills', 'copies'):
        if k not in m:
            problems.append('studio/manifest.json has no "%s"' % k)
    ids = set()
    for t in m.get('tools', []):
        for k in ('id', 'name', 'page', 'kind', 'what', 'when', 'sources', 'outputs', 'run', 'skill', 'ships'):
            if k not in t:
                problems.append('tool %s has no "%s"' % (t.get('id', '?'), k))
        if t.get('id') in ids:
            problems.append('duplicate tool id: ' + t['id'])
        ids.add(t.get('id'))
        page = os.path.join(ROOT, t.get('page', '').split('#')[0])
        if not os.path.isfile(page):
            problems.append('tool %s: page %s is missing' % (t['id'], t['page']))
            continue
        html = open(page, encoding='utf8').read()
        if not re.search(r'''<script[^>]*src=["']studio/studio\.js[^"']*["'][^>]*data-tool=["']%s["']''' % re.escape(t['id']), html):
            problems.append('%s does not load the studio bar: <script defer src="studio/studio.js" data-tool="%s"></script>' % (t['page'].split('#')[0], t['id']))
        if 'studio/studio.css' not in html:
            problems.append('%s does not load studio/studio.css' % t['page'].split('#')[0])
        if not os.path.isfile(os.path.join(ROOT, '.claude', 'skills', t.get('skill', ''), 'SKILL.md')):
            problems.append('tool %s names skill %s, which has no .claude/skills/%s/SKILL.md' % (t['id'], t.get('skill'), t.get('skill')))
    for s in m.get('skills', []):
        if not os.path.isfile(os.path.join(ROOT, s['path'])):
            problems.append('skill %s: %s is missing' % (s['name'], s['path']))
    for d in sorted(os.listdir(os.path.join(ROOT, '.claude', 'skills'))):
        if d not in {s['name'] for s in m.get('skills', [])}:
            problems.append('skill %s is not listed in studio/manifest.json "skills"' % d)
    if not os.path.exists(BAR_OUT) or open(BAR_OUT, encoding='utf8').read() != bar_js(m):
        problems.append('studio/studio.js is out of date: run python tools/design_system.py build')
    # the site: one studio block, and nothing outside it reaches the studio
    idx = open(os.path.join(ROOT, 'index.html'), encoding='utf8').read()
    if idx.count(MARK_A) != 1 or idx.count(MARK_B) != 1:
        problems.append('index.html needs exactly one <!-- studio: ... --> ... <!-- /studio --> block')
    rest = strip_studio(idx)
    if 'studio/' in rest or 'draftbar' in rest:
        problems.append('index.html reaches the studio outside its studio block (move it inside, or the live site breaks)')
    # dry-run release
    with tempfile.TemporaryDirectory() as tmp:
        out = os.path.join(tmp, 'live')
        _, unmatched = release(out, quiet=True)
        problems += ['live.keep pattern matches nothing: ' + u for u in unmatched]
        problems += release_problems(out, m)
    for p in problems:
        print('STUDIO', p)
    print('studio: %d problem(s), %d tools, release dry run %s' % (len(problems), len(m.get('tools', [])), 'clean' if not problems else 'see above'))
    return 1 if problems else 0


# ---------------------------------------------------------------- assemble (GitHub Pages)

def copytree(src, dst, exclude=()):
    ex = {'.git', '.github'} | set(exclude)

    def ignore(d, names):
        r = rel(d, src)
        return [n for n in names if n in ex or (r + '/' + n if r != '.' else n) in ex]
    shutil.copytree(src, dst, ignore=ignore, dirs_exist_ok=True)


def label_copy(dst, name):
    """Older checkouts (before the studio) name their copy in the draft bar text."""
    p = os.path.join(dst, 'index.html')
    if os.path.exists(p):
        s = open(p, encoding='utf8').read()
        open(p, 'w', encoding='utf8', newline='\n').write(s.replace('Draft site · not for release · ', '%s copy · draft site · not for release · ' % name))


def assemble(site, main, staging, dev):
    me = load()
    os.makedirs(site, exist_ok=True)
    mm = load(main) or me
    if mm['release'].get('production', True):
        copytree(main, site)
        print('production: tooled draft (main)')
    else:
        release(site, main, mm)
        copytree(main, os.path.join(site, 'studio'))
        print('production: LIVE site (main released); tooled main at studio/')
    for name, src in (('staging', staging), ('dev', dev)):
        mb = load(src) or me
        dst = os.path.join(site, name)
        if mb['release'].get(name, True):
            copytree(src, dst, HEAVY)
            label_copy(dst, name.capitalize())
            print('%s: tooled (without %s)' % (name, ', '.join(HEAVY)))
        else:
            release(dst, src, mb)
            print('%s: LIVE' % name)
    release(os.path.join(site, 'live'), main, mm)
    print('live: released main, for review before the switch')
    open(os.path.join(site, '.nojekyll'), 'w').close()


def main():
    a = sys.argv[1:]
    cmd = a[0] if a else 'about'
    if cmd == 'about':
        about(a[1] if len(a) > 1 else None)
    elif cmd == 'status':
        status()
    elif cmd == 'build':
        build()
    elif cmd == 'check':
        sys.exit(check())
    elif cmd == 'refresh':
        refresh([x for x in a[1:] if not x.startswith('--')], '--history' in a)
    elif cmd == 'release' and len(a) > 1:
        src = a[a.index('--from') + 1] if '--from' in a else ROOT
        out = os.path.abspath(a[1])
        release(out, src)
        m = load(src) or load()
        ps = release_problems(out, m)
        for p in ps:
            print('STUDIO', p)
        sys.exit(1 if ps else 0)
    elif cmd == 'assemble' and len(a) > 1 and all(f in a for f in ('--main', '--staging', '--dev')):
        g = lambda f: a[a.index(f) + 1]
        assemble(a[1], g('--main'), g('--staging'), g('--dev'))
    else:
        print(__doc__)
        sys.exit(2)


if __name__ == '__main__':
    main()
