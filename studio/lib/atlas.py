"""Style atlas index: the image-to-text descriptions of every generated or reference image, counted and joined.

    python studio/studio.py atlas

Reads <data.atlas>/images/*.json (one description per image, schemas/image-description.schema.json, written by the
describe step of the studio-image-loop skill) and writes <data.atlas>/atlas.json for the viewer studio/web/atlas.html:
  images     every description with the image's path (found in data.concepts, the gallery, or beside the JSON)
  keywords   text-to-image keywords counted across images (folded: case, plurals, hyphens), with the images using each
  fields     the top phrases of every list field (palette, composition, rendering, motifs ...)
  families   images per style_family
  fit        brand_fit histogram, and keywords that lean high-fit versus low-fit (what scored, what failed)
  docs       the atlas text (STYLE-ATLAS.md) and the prompt kit (data.prompt_kit) when they exist
A project may run its own analysis first (config atlas.producer, e.g. curated concept tags); its keywords.json is
linked from atlas.json as "extra".
"""
import glob
import json
import os
import re
import unicodedata
from collections import Counter, defaultdict

import config

LISTS = ('art_direction', 'composition', 'layout_devices', 'palette', 'typography', 'rendering', 'line_and_texture',
         'motifs', 'ui_patterns', 'motion_implied', 'mood', 'strengths', 'weaknesses')


def fold(s):
    s = unicodedata.normalize('NFKC', str(s)).lower().replace('-', ' ')
    s = re.sub(r'[^\w\s#%./]', ' ', s)
    s = ' '.join(w[:-1] if len(w) > 4 and w.endswith('s') and not w.endswith('ss') else w for w in s.split())
    return s.strip()


def find_image(P, name, here, index):
    if not name:
        return None
    if name in index:
        return index[name]
    for d in (P.cfg['data']['concepts'], os.path.dirname(here)):
        p = P.path(d, name) if not os.path.isabs(d) else os.path.join(d, name)
        if os.path.isfile(p):
            return P.rel(p)
    return None


def run(P=None):
    P = P or config.load()
    base = P.path(P.cfg['data']['atlas'])
    files = sorted(glob.glob(os.path.join(base, 'images', '*.json')))
    gal = P.path(P.cfg['data']['gallery'])
    index = {}
    if os.path.exists(gal):
        for it in json.load(open(gal, encoding='utf8')).get('items', []):
            index.setdefault(os.path.basename(it['src']), it['src'])
            if it.get('thumb'):
                index.setdefault('thumb:' + os.path.basename(it['src']), it['thumb'])
    images, kw, kw_imgs, fields, fam, fit = [], Counter(), defaultdict(set), defaultdict(Counter), Counter(), Counter()
    hi, lo = Counter(), Counter()
    for f in files:
        try:
            d = json.load(open(f, encoding='utf8'))
        except ValueError:
            print('  not JSON, skipped: ' + P.rel(f))
            continue
        name = d.get('file') or os.path.splitext(os.path.basename(f))[0] + '.png'
        d['_src'] = find_image(P, name, f, index)
        d['_thumb'] = index.get('thumb:' + name)
        d['_json'] = P.rel(f)
        images.append(d)
        bf = d.get('brand_fit')
        if isinstance(bf, (int, float)):
            fit[int(bf)] += 1
        if d.get('style_family'):
            fam[fold(d['style_family'])] += 1
        ks = {fold(k) for k in d.get('t2i_keywords', []) if str(k).strip()}
        for k in ks:
            kw[k] += 1
            kw_imgs[k].add(name)
            if isinstance(bf, (int, float)):
                (hi if bf >= 4 else lo if bf <= 2 else Counter())[k] += 1
        for fld in LISTS:
            for v in {fold(x) for x in d.get(fld, []) if str(x).strip()}:
                fields[fld][v] += 1
    n_hi, n_lo = sum(1 for i in images if (i.get('brand_fit') or 0) >= 4), sum(1 for i in images if 0 < (i.get('brand_fit') or 0) <= 2)
    lean = []
    for k, c in kw.items():
        if c >= 3 and (n_hi and n_lo):
            a, b = hi[k] / n_hi, lo[k] / n_lo
            lean.append((round(a - b, 3), k, hi[k], lo[k]))
    lean.sort()
    md = os.path.join(base, 'STYLE-ATLAS.md')
    kit = P.path(P.cfg['data']['prompt_kit'])
    extra = os.path.join(base, 'keywords.json')
    out = {
        'about': 'Generated by python %s/studio.py atlas from %s/images/*.json. Do not edit.' % (P.kit_rel, P.cfg['data']['atlas']),
        'count': len(images),
        'images': images,
        'keywords': [{'k': k, 'n': c, 'images': sorted(kw_imgs[k])[:60]} for k, c in kw.most_common(400)],
        'fields': {fld: fields[fld].most_common(40) for fld in LISTS if fields[fld]},
        'families': fam.most_common(),
        'fit': {'histogram': {str(k): fit[k] for k in sorted(fit)}, 'high': n_hi, 'low': n_lo,
                'scored': [[k, h, l] for _, k, h, l in reversed(lean[-30:])], 'failed': [[k, h, l] for _, k, h, l in lean[:30]]},
        'docs': {'atlas': P.rel(md) if os.path.exists(md) else None, 'prompt_kit': P.rel(kit) if os.path.exists(kit) else None,
                 'extra': P.rel(extra) if os.path.exists(extra) else None},
    }
    os.makedirs(base, exist_ok=True)
    json.dump(out, open(os.path.join(base, 'atlas.json'), 'w', encoding='utf8', newline='\n'), ensure_ascii=False, separators=(',', ':'))
    print('wrote %s/atlas.json: %d images, %d keywords, %d families' % (P.cfg['data']['atlas'], len(images), len(kw), len(fam)))
