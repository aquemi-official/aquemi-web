import config
import pages as pagesmod

PY = sys.executable or 'python3'
ENV = dict(os.environ, PYTHONHASHSEED='0')  # generators run deterministic: the same input writes the same files


def env(P):
    """The environment generators run in: deterministic hashing, plus the project's config "env" (a time zone, say),
    so every machine writes the same files."""
    return dict(ENV, **{k: str(v) for k, v in P.cfg.get('env', {}).items()})
MARK_A, MARK_B = '<!-- studio:', '<!-- /studio -->'


def argv(cmd):
    """A config command (list, or a string split on spaces) with "python" mapped to this interpreter."""
    c = cmd.split() if isinstance(cmd, str) else list(cmd)
    return [PY if x in ('python', 'python3') else x for x in c]


# ================================================================ build

def bar_config(P):
    c = P.cfg
    return {
        'project': {'name': c['project']['name'], 'repo': c['project'].get('repo', ''), 'url': c['project'].get('url', '')},
        'kit': P.kit_rel, 'version': P.kitinfo['version'],
        'release': {k: v for k, v in c['release'].items() if isinstance(v, bool)},
        'copies': [{'id': x['id'], 'path': x['path'], 'label': x.get('label', x['id']), 'branch': x.get('branch', '')} for x in c['copies']],
        'tools': [{k: t[k] for k in ('id', 'name', 'page', 'what', 'production_only', 'origin') if k in t} for t in P.tools() if t.get('page')],
        'site': {k: c['site'][k] for k in ('entry', 'current', 'root', 'toggles', 'notes_label')},
        'theme': c['theme'],
        'data': c['data'],
    }


def bar_js(P):
    src = open(os.path.join(P.kit, 'web', 'src', 'bar.js'), encoding='utf8').read()
    head = '/* Generated by python %s/studio.py build from %s/web/src/bar.js and studio.config.json. Do not edit. */\n' % (P.kit_rel, P.kit_rel)
    return head + src.replace('/*@CONFIG@*/null', json.dumps(bar_config(P), ensure_ascii=False, separators=(',', ':')))


def write(path, text):
    if os.path.exists(path) and open(path, encoding='utf8').read() == text:
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w', encoding='utf8', newline='\n').write(text)
    return True


def history_sw(P):
    """The page-history service worker must sit in the history folder (its scope); the kit keeps the source."""
    d = P.path(P.cfg['data']['history'])
    if os.path.isdir(d):
        write(os.path.join(d, 'sw.js'), open(os.path.join(P.kit, 'web', 'history-sw.js'), encoding='utf8').read())


def hub_json(P):
    """Everything the hub (web/index.html) shows: the merged tool list, skills, copies, release, live.keep."""
    c = P.cfg
    return json.dumps({
        'about': 'Generated by python %s/studio.py build from studio.config.json and %s/kit.json. Do not edit.' % (P.kit_rel, P.kit_rel),
        'project': c['project'], 'brand': {k: c['brand'][k] for k in ('book', 'plan', 'summary') if c['brand'].get(k)},
        'kit': {'path': P.kit_rel, 'version': P.kitinfo['version']},
        'tools': P.tools(), 'skills': P.skills(), 'notes': c['notes'], 'copies': c['copies'], 'release': c['release'],
        'branches': c['branches'], 'live': c['live'], 'external': c['external'], 'data': c['data'],
        'steps': [{'id': s['id'], 'label': s['label']} for s in steps(P)],
        'checks': [' '.join(x) if isinstance(x, list) else x for x in c.get('checks', [])],
    }, ensure_ascii=False, indent=1) + '\n'


def build(P=None, quiet=False):
    P = P or config.load()
    write(os.path.join(P.kit, 'web', 'studio.js'), bar_js(P))
    write(P.path(P.cfg['data']['dir'], 'studio.json'), hub_json(P))
    n = len(pagesmod.write_index(P))
    history_sw(P)
    if not quiet:
        print('wrote %s/web/studio.js (studio bar, %d tools) and %s/pages.json (%d pages)' % (
            P.kit_rel, len(P.tools()), P.cfg['data']['dir'], n))


